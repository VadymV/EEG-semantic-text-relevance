"""
This script generates the results of the benchmark experiments.
Run it with ``poetry run python generate_results.py --project_path=path``
The project_path should point to the files generated by ``benchmark.py``
The generated results are saved to a log_results.log file.
"""

import argparse
import glob
import logging
import os

import numpy as np
import pandas as pd
import seaborn as sns
import torch.nn
from matplotlib import pyplot as plt
from torch import tensor
from torchmetrics.classification import (
    BinaryCohenKappa,
    BinaryPrecision,
    BinaryRecall,
    BinaryMatthewsCorrCoef,
    BinaryAUROC,
    BinaryF1Score,
)

from src.releegance.misc.utils import (
    set_logging,
    set_seed,
    create_args,
    calibrate_probability,
)

_grouping_columns = ["seed", "user", "model", "strategy"]


def run(file_pattern: str, args: argparse.Namespace, axes):
    # Read predictions:
    filepaths = glob.glob(os.path.join(args.project_path, file_pattern))
    if not filepaths:
        logging.warning("No files found. Quitting...")
        return
    if file_pattern.startswith("s"):
        column = 1
    if file_pattern.startswith("w"):
        column = 0
    results = []
    for fp in filepaths:
        with open(fp, "r") as f:
            logging.info("Reading %s", fp)
            results.append(pd.read_pickle(f.name))
    results = pd.concat(results)

    def log_predictions(stage: str):
        for model_name in results["model"].unique():
            model_probs = results.loc[results["model"] == model_name, "predictions"]
            logging.info(
                "Model %s predictions %s — mean: %.3f, median: %.3f, std: %.3f, min: %.3f, max: %.3f",
                model_name,
                stage,
                model_probs.mean(),
                model_probs.median(),
                model_probs.std(),
                model_probs.min(),
                model_probs.max(),
            )

    # Apply sigmoid to predictions based on the model type:
    mask = results["model"].isin(["eegnet", "lstm", "uercm"])
    masked_results = results.loc[mask]
    logits = torch.tensor(masked_results["predictions"].values, dtype=torch.float32)
    probs = torch.sigmoid(logits).numpy()
    results.loc[mask, "predictions"] = probs

    log_predictions("before calibration")

    if file_pattern.startswith("s"):
        results["ratio_pos_neg"] = 1.0

    # Calibrate probabilities so that the natural 0.5 threshold is correct:
    if file_pattern.startswith("w"):
        results["predictions"] = results.apply(
            lambda x: calibrate_probability(x["predictions"], x["ratio_pos_neg"]),
            axis=1,
        )

    log_predictions("after calibration")

    # Calculate classification metrics:
    groups = results.groupby(_grouping_columns)
    mcc = groups.apply(
        lambda x: BinaryMatthewsCorrCoef()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    mcc.rename(columns={0: "mcc"}, inplace=True)

    f1 = groups.apply(
        lambda x: BinaryF1Score()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    f1.rename(columns={0: "f1"}, inplace=True)

    kappa = groups.apply(
        lambda x: BinaryCohenKappa()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    kappa.rename(columns={0: "kappa"}, inplace=True)

    precision = groups.apply(
        lambda x: BinaryPrecision()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    precision.rename(columns={0: "precision"}, inplace=True)

    recall = groups.apply(
        lambda x: BinaryRecall()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    recall.rename(columns={0: "recall"}, inplace=True)

    auc = groups.apply(
        lambda x: BinaryAUROC()(
            tensor(x.predictions.tolist()), tensor(x.targets.tolist())
        ).item(),
        include_groups=False,
    ).reset_index()
    auc.rename(columns={0: "auc"}, inplace=True)

    # Concatenate metrics:
    metrics = mcc.merge(precision, on=_grouping_columns)
    metrics = metrics.merge(kappa, on=_grouping_columns)
    metrics = metrics.merge(recall, on=_grouping_columns)
    metrics = metrics.merge(auc, on=_grouping_columns)
    metrics = metrics.merge(f1, on=_grouping_columns)

    all_metric_cols = ["auc", "precision", "recall", "f1"]

    # summary[model][strategy] = dict of metric -> (mean, std)
    summary = {}
    for model in metrics.model.unique():
        summary[model] = {}
        for strategy in metrics.strategy.unique()[::-1]:
            logging.info("\n\nModel: %s, Strategy: %s", model, strategy)
            subset = metrics[
                (metrics["model"] == model) & (metrics["strategy"] == strategy)
            ]
            per_participant = subset.groupby("user")[all_metric_cols].mean()
            summary[model][strategy] = {}
            for metric in ["auc", "precision", "recall", "f1"]:
                mean = per_participant[metric].mean()
                std = per_participant[metric].std()
                summary[model][strategy][metric] = (mean, std)
                logging.info("%s: %.2f +- %.2f", metric, mean, std)

    num_models = len(metrics["model"].unique())
    num_participants = len(metrics["user"].unique())
    if num_models != 6 and num_participants != 15:
        raise ValueError(
            "The number of models should be 6, and the number of participants should be 15."
        )
    plot_metrics = metrics[metrics["model"] != "lda_control"]
    num_plot_models = len(plot_metrics["model"].unique())
    strategy_dependent = np.empty((num_plot_models, num_participants))
    strategy_independent = np.empty((num_plot_models, num_participants))
    for participant_id, participant in enumerate(plot_metrics["user"].unique()):
        d = plot_metrics[(plot_metrics["user"] == participant)]
        for model_id, model in enumerate(plot_metrics.model.unique()):
            for strategy in plot_metrics.strategy.unique()[::-1]:
                for metric in ["auc", "precision", "recall"]:
                    mean = d[(d["model"] == model) & (d["strategy"] == strategy)][
                        metric
                    ].mean()

                    if metric == "auc" and strategy == "participant-dependent":
                        strategy_dependent[model_id, participant_id] = round(mean, 2)

                    if metric == "auc" and strategy == "participant-independent":
                        strategy_independent[model_id, participant_id] = round(mean, 2)

    cmap = sns.cubehelix_palette(
        light=1, gamma=0.6, n_colors=50, rot=-0.4, as_cmap=True
    )
    sns.set(font_scale=2)
    sns.set_theme(style="white")

    vmin, vmax = 0.4, 0.95

    model_dict = {
        "eegnet": "EEGNet",
        "lda": "LDA",
        "lr": "LR",
        "lstm": "LSTM",
        "uercm": "UERCM",
        "lda_control": "Control",
    }

    model_names = []
    for model_ in plot_metrics["model"].unique():
        model_names.append(model_dict[model_])

    # Plot within-subject
    axes[0, column].imshow(strategy_dependent, cmap=cmap, vmin=vmin, vmax=vmax)
    for (i, j), z in np.ndenumerate(strategy_dependent):
        color = "white" if z > 0.7 else "black"
        axes[0, column].text(
            j, i, f"{z}", ha="center", va="center", size=11, color=color
        )
    if column == 0:
        axes[0, column].set_title("Word relevance classification task", fontsize=16)
        axes[0, column].set_yticks(np.arange(len(model_names)))
        axes[0, column].set_yticklabels(model_names, fontsize=14)
    if column == 1:
        axes[0, column].set_title("Sentence relevance classification task", fontsize=16)
        axes[0, column].annotate(
            "Within-subject",
            xy=(1.02, 0.5),
            xycoords="axes fraction",
            fontsize=16,
            ha="left",
            va="center",
            rotation=90,
        )

    # Plot cross-subject
    axes[1, column].imshow(strategy_independent, cmap=cmap, vmin=vmin, vmax=vmax)
    for (i, j), z in np.ndenumerate(strategy_independent):
        color = "white" if z > 0.7 else "black"
        axes[1, column].text(
            j, i, f"{z}", ha="center", va="center", size=10, color=color
        )
    if column == 0:
        axes[1, column].set_yticks(np.arange(len(model_names)))
        axes[1, column].set_yticklabels(model_names, fontsize=14)
        axes[1, column].annotate(
            "Model",
            xy=(-0.22, 1.0),
            xycoords="axes fraction",
            fontsize=16,
            ha="left",
            va="center",
            rotation=90,
        )
    if column == 1:
        axes[1, column].annotate(
            "Cross-subject",
            xy=(1.02, 0.5),
            xycoords="axes fraction",
            fontsize=16,
            ha="left",
            va="center",
            rotation=90,
        )
        axes[1, column].annotate(
            "Participant's ID",
            xy=(-0.0, -0.65),
            xycoords="axes fraction",
            fontsize=16,
            ha="center",
            va="bottom",
        )

    axes[1, column].set_xticks(np.arange(len(metrics["user"].unique())))
    axes[1, column].set_xticklabels(metrics["user"].unique(), fontsize=14, rotation=90)

    return summary


def generate_latex_table(word_summary: dict, sentence_summary: dict, output_path: str):
    model_dict = {
        "eegnet": "EEGNet",
        "lda": "LDA$^*$",
        "lr": "LR$^*$",
        "lstm": "LSTM",
        "uercm": "UERCM",
        "lda_control": "Control",
    }
    strategies = ["participant-independent", "participant-dependent"]
    metrics = ["auc", "precision", "recall", "f1"]

    def get_best(summary):
        """For each (strategy, metric) column, find the highest mean across all models."""
        best = {}
        for strategy in strategies:
            for metric in metrics:
                best[(strategy, metric)] = max(
                    summary[m][strategy][metric][0] for m in summary
                )
        return best

    def cell(mean, std, best_val):
        s = f"{mean:.2f} ({std:.2f})"
        return rf"\textbf{{{s}}}" if round(mean, 2) == round(best_val, 2) else s

    def model_rows(summary, best):
        rows = []
        for model_key, model_label in model_dict.items():
            if model_key not in summary:
                continue
            cols = []
            for strategy in strategies:
                for metric in metrics:
                    m, s = summary[model_key][strategy][metric]
                    cols.append(cell(m, s, best[(strategy, metric)]))
            rows.append(f"        {model_label} & " + " & ".join(cols) + " \\\\")
        return rows

    word_best = get_best(word_summary)
    sent_best = get_best(sentence_summary)

    lines = [
        r"\begin{table*}",
        r"    \caption{Word relevance and sentence relevance binary classification results averaged over all participants. The best scores are highlighted in bold. The value inside parentheses denotes standard deviation. $^*$ means that the model is trained from scratch in the within-subject strategy, as fine-tuning is not supported for this model. Control is the LDA model trained with randomly shuffled labels.}",
        r"    \label{tab:results}",
        r"    \centering",
        r"    \setlength{\tabcolsep}{8pt}",
        r"    \begin{tabular}{lcccccccc}",
        r"        \toprule",
        r"        \multirow{3}{*}{\thead{Model}} & \multicolumn{4}{c}{\thead{Cross-subject}} & \multicolumn{4}{c}{\thead{Within-subject}}\\",
        r"        \cmidrule(rl){2-5} \cmidrule(rl){6-9}",
        r"         & \thead{AUC} & \thead{Precision} & \thead{Recall} & \thead{F1} & \thead{AUC} & \thead{Precision} & \thead{Recall} & \thead{F1}\\",
        r"        \midrule",
        r"        & \multicolumn{8}{c}{Word relevance classification task} \\",
        r"        \midrule",
    ]
    lines += model_rows(word_summary, word_best)

    lines += [
        r"        \midrule",
        r"        & \multicolumn{8}{c}{Sentence relevance classification task} \\",
        r"        \midrule",
    ]
    lines += model_rows(sentence_summary, sent_best)

    lines += [
        r"        \bottomrule",
        r"    \end{tabular}",
        r"\end{table*}",
    ]

    table = "\n".join(lines)
    with open(output_path, "w") as f:
        f.write(table)
    logging.info("LaTeX table saved to %s", output_path)


def plot_auc_curves(
    file_patterns: list, args: argparse.Namespace, title: str, output_path: str
):
    """
    Plots train and val AUC learning curves averaged over all participants,
    seeds, and reading tasks. One subplot per (model, strategy) combination.
    Shaded area = 1 SD.
    """
    all_results = []
    for file_pattern in file_patterns:
        filepaths = glob.glob(os.path.join(args.project_path, file_pattern))
        for fp in filepaths:
            with open(fp, "r") as f:
                all_results.append(pd.read_pickle(f.name))
    if not all_results:
        logging.warning("No files found for AUC curve plot.")
        return
    results = pd.concat(all_results)

    # Skip rows from sklearn models (empty histories)
    results = results[results["train_auc_history"].apply(lambda x: len(x) > 0)]
    if results.empty:
        logging.warning("No AUC history data found (only sklearn models?).")
        return

    # Deduplicate: one history per (seed, user, model, strategy, reading_task)
    history_cols = ["seed", "user", "model", "strategy", "reading_task"]
    histories = results[
        history_cols + ["train_auc_history", "val_auc_history"]
    ].drop_duplicates(subset=history_cols)

    models_order = sorted(histories["model"].unique())
    strategies = sorted(histories["strategy"].unique())

    n_models = len(models_order)
    n_strategies = len(strategies)

    model_dict = {
        "eegnet": "EEGNet",
        "lstm": "LSTM",
        "uercm": "UERCM",
    }

    fig, axes = plt.subplots(
        nrows=n_strategies,
        ncols=n_models,
        figsize=(5 * n_models, 4 * n_strategies),
        gridspec_kw={"hspace": 0.35, "wspace": 0.3},
    )
    if n_strategies == 1:
        axes = axes[np.newaxis, :]
    if n_models == 1:
        axes = axes[:, np.newaxis]

    for si, strategy in enumerate(strategies):
        for mi, model_name in enumerate(models_order):
            ax = axes[si, mi]
            subset = histories[
                (histories["model"] == model_name) & (histories["strategy"] == strategy)
            ]
            if subset.empty:
                ax.set_visible(False)
                continue

            def pad_and_stack(series):
                lists = series.tolist()
                max_len = max(len(h) for h in lists)
                arr = np.full((len(lists), max_len), np.nan)
                for i, h in enumerate(lists):
                    arr[i, : len(h)] = h
                return arr

            train_arr = pad_and_stack(subset["train_auc_history"])
            val_arr = pad_and_stack(subset["val_auc_history"])

            epochs = np.arange(1, train_arr.shape[1] + 1)
            for arr, label, color in [
                (train_arr, "Train AUC", "steelblue"),
                (val_arr, "Val AUC", "darkorange"),
            ]:
                mean = np.nanmean(arr, axis=0)
                sd = np.nanstd(arr, axis=0)
                ax.plot(epochs, mean, label=label, color=color)
                ax.fill_between(epochs, mean - sd, mean + sd, alpha=0.2, color=color)

            ax.set_title(
                f"{model_dict.get(model_name, model_name)}\n{strategy}", fontsize=11
            )
            ax.set_xlabel("Epoch", fontsize=9)
            ax.set_ylabel("AUC", fontsize=9)
            ax.set_ylim(0.0, 1.0)
            ax.legend(fontsize=8)

    fig.suptitle(title, fontsize=14)
    plt.savefig(output_path, format="pdf", bbox_inches="tight")
    logging.info("Saved AUC curve plot to %s", output_path)


if __name__ == "__main__":
    parser = create_args(seeds_args=False, benchmark_args=False)
